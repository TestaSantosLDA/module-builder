#!/usr/bin/env python3
"""Imports catalogue houses from JSON files (one per house) into src/model/catalog-houses.ts.

Usage: python3 scripts/import-houses.py <folder with *.json>
Each JSON: {id, family, name, page, catalogArea, modules:[{type,x,y,rot,z}], newTypes:{key:{name,w,h,kind}}, notes}
Re-run it when Jular sends real dimensions and the JSON files are updated.
"""
import json, re, sys, pathlib

# Same key used with different sizes by different houses: rename per house.
RENAME = {
    ('original-t2c', 'quartoOpc'): 'quartoOpcP', ('original-t3b', 'quartoOpc'): 'quartoOpcP', ('original-t3e', 'quartoOpc'): 'quartoOpcP',
    ('original-t2c', 'antecamara'): 'antecamaraE', ('original-t3b', 'antecamara'): 'antecamaraE',
}
RENAMED_NAMES = {'quartoOpcP': 'Quarto opcional pequeno', 'antecamaraE': 'Antecâmara estreita'}

# Palette category and plan sketch for each new type.
CAT = {
    'sala': ['cozinhaGD', 'salaD', 'salaG', 'salaXL', 'salaComum', 'salaSW1', 'salaSW2', 'salaSW3'],
    'quarto': ['quartoGD', 'quartoMD', 'quartoG', 'quartoOpc', 'quartoOpcP', 'quartoRoup', 'suiteOri', 'quartoSW'],
    'wc': ['wcArrD', 'banhos', 'isDupla', 'isSuites', 'wcArrumos', 'hallWcSW1', 'circWcSW'],
    'circ': ['antecamara', 'antecamaraE', 'circulacao'],
    'deck': ['deckD', 'deckO', 'deckOri', 'deckFrente', 'deckTopo', 'deckCorrido', 'deckSW1', 'deckSW'],
}
SKETCH = {'sala': 'sala', 'quarto': 'quarto', 'wc': 'entrada', 'circ': None, 'deck': 'deck'}
SKETCH_OVERRIDE = {'suiteOri': 'suite', 'cozinhaGD': 'cozinha'}
CAT_OF = {k: c for c, ks in CAT.items() for k in ks}

src = pathlib.Path(sys.argv[1])
houses, types = [], {}
for f in sorted(src.glob('*.json')):
    d = json.loads(f.read_text())
    hid = d['id']
    for k, t in (d.get('newTypes') or {}).items():
        key = RENAME.get((hid, k), k)
        t = {**t, 'name': RENAMED_NAMES.get(key, t['name'])}
        prev = types.get(key)
        if prev and (prev['w'], prev['h'], prev['kind']) != (t['w'], t['h'], t['kind']):
            sys.exit(f'type {key} has two sizes: {prev} vs {t} ({hid})')
        if key not in CAT_OF:
            sys.exit(f'type {key} ({hid}) has no category: add it to CAT')
        types[key] = t
    m = re.search(r'Área Bruta\s*([\d.,]+)\s*m', d['catalogArea'])
    area = (m.group(1) + ' m²') if m else d['catalogArea']
    label = d['name'].split()[-1]
    plan = [{**p, 'type': RENAME.get((hid, p['type']), p['type'])} for p in d['modules']]
    houses.append({'id': hid, 'family': d['family'], 'label': label, 'name': d['name'], 'page': d['page'], 'catalogArea': area, 'plan': plan})

def js(v): return json.dumps(v, ensure_ascii=False)
out = ['// GENERATED by scripts/import-houses.py from the per-house JSON files. Do not edit by hand.',
       '// Sizes are ESTIMATED from the catalogue plans (no dimensions printed); see the JSON notes.',
       "import type { ModuleType } from './catalog.js';", '',
       'export const EXTRA_TYPES = {']
for k, t in sorted(types.items(), key=lambda kv: (list(CAT).index(CAT_OF[kv[0]]), kv[0])):
    c = CAT_OF[k]; sk = SKETCH_OVERRIDE.get(k, SKETCH[c])
    out.append(f"  {k}: {{ name: {js(t['name'])}, w: {t['w']}, h: {t['h']}, kind: {js(t['kind'])}, cat: {js(c)}{', sketch: ' + js(sk) if sk else ''}{', pergola: true' if t.get('pergola') else ''} }},")
out += ['} as const satisfies Record<string, ModuleType>;', '',
        'export interface CatalogHouse { id: string; family: string; label: string; name: string; page: number; catalogArea: string; plan: { type: string; x: number; y: number; rot: number; z: number }[] }', '',
        'export const CATALOG_HOUSES: CatalogHouse[] = [']
for h in houses:
    out.append('  ' + js(h) + ',')
out.append('];\n')
pathlib.Path(__file__).resolve().parent.parent.joinpath('src/model/catalog-houses.ts').write_text('\n'.join(out))
print(f'{len(houses)} houses, {len(types)} new types')
